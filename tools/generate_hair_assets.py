VIEWBOX = "0 0 200 260"

REPO_ROOT = Path(__file__).resolve().parents[1]
KB_PATH = REPO_ROOT / "backend" / "app" / "knowledge" / "hairstyles.yaml"
OUT_DIR = REPO_ROOT / "frontend" / "public" / "assets" / "hair"


@dataclass(frozen=True)
class Hair:
    """Silhouette parameters for one style family."""

    top: float = 10.0  # extra height of hair above the scalp
    side: float = 112.0  # y-coord the side hair falls to (112 ears .. 230 long)
    back: float = 112.0  # y-coord the back hair falls to (back view)
    full: float = 8.0  # horizontal fullness beyond the face
    fringe: float = 0.2  # forehead coverage 0..1
    part: str = "none"  # none | center | side
    bun: bool = False
    ponytail: bool = False
    afro: bool = False
    curly: bool = False
    buzz: bool = False
    fade: bool = False
    crest: bool = False  # central faux-hawk ridge
    pomp: bool = False  # pompadour/quiff front volume
    braids: bool = False


