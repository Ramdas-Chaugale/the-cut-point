def _svg(inner: str) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VIEWBOX}" '
        f'role="img" width="200" height="260">\n{inner}\n</svg>\n'
    )


def _curly_edge(cx: float, cy: float, rx: float, ry: float, n: int) -> str:
    """A scalloped (bumpy) ellipse to suggest curls/afro texture."""
    import math

    pts = []
    for i in range(n):
        a = 2 * math.pi * i / n
        bump = 1.0 + (0.12 if i % 2 == 0 else -0.02)
        pts.append((cx + rx * bump * math.cos(a), cy + ry * bump * math.sin(a)))
    d = "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + " Z"
    return f'<path d="{d}" fill="{HAIR}"/>'


def _shoulders() -> str:
    return f'<path d="M28,260 C40,206 70,192 100,192 C130,192 160,206 172,260 Z" fill="{GARMENT}"/>'


def front(p: Hair) -> str:
    cx = 100.0
    top = 52 - p.top
    half = 40 + p.full
    e: list[str] = []

    # hair back mass (length + fullness), behind the face
    if p.afro:
        e.append(_curly_edge(cx, 96, half, half, 22))
    elif not p.buzz:
        e.append(
            f'<path d="M{cx-half},96 C{cx-half},{top} {cx+half},{top} {cx+half},96 '
            f"L{cx+half},{p.side} C{cx+half},{p.side+18} {cx-half},{p.side+18} "
            f'{cx-half},{p.side} Z" fill="{HAIR}"/>'
        )

    e.append(_shoulders())
    e.append(f'<rect x="86" y="146" width="28" height="42" rx="11" fill="{SKIN}"/>')
    e.append(f'<ellipse cx="{cx}" cy="104" rx="40" ry="52" fill="{SKIN}"/>')
    e.append(f'<ellipse cx="60" cy="112" rx="7" ry="11" fill="{SKIN_SHADE}"/>')
    e.append(f'<ellipse cx="140" cy="112" rx="7" ry="11" fill="{SKIN_SHADE}"/>')

    # top cap / hairline over the scalp
    if p.buzz:
        # filled cap following the skull arc down to the hairline
        e.append(f'<path d="M63,86 A40,52 0 0 1 137,86 C118,81 82,81 63,86 Z" fill="{HAIR}"/>')
    elif not p.afro:
        capw = 44.0
        brow = 74 + p.fringe * 20
        e.append(
            f'<path d="M{cx-capw},90 C{cx-capw},{top+4} {cx+capw},{top+4} {cx+capw},90 '
            f'C{cx+22},{brow} {cx-22},{brow} {cx-capw},90 Z" fill="{HAIR}"/>'
        )

    # fringe over the forehead
    if p.fringe >= 0.4 and not p.buzz and not p.afro:
        fy = 70 + p.fringe * 26
        if p.part == "center":
            e.append(
                f'<path d="M{cx},86 C{cx-26},{fy} {cx-44},92 {cx-44},86 '
                f'C{cx-30},78 {cx-8},80 {cx},86 Z" fill="{HAIR}"/>'
            )
            e.append(
                f'<path d="M{cx},86 C{cx+26},{fy} {cx+44},92 {cx+44},86 '
                f'C{cx+30},78 {cx+8},80 {cx},86 Z" fill="{HAIR}"/>'
            )
        else:
            e.append(
                f'<path d="M{cx-44},84 C{cx-18},{fy} {cx+22},{fy-6} {cx+44},86 '
                f'L{cx+44},78 L{cx-44},80 Z" fill="{HAIR}"/>'
            )

    # specials
    if p.pomp:
        e.append(
            f'<path d="M{cx-38},90 C{cx-34},{top-12} {cx+34},{top-12} {cx+38},90 Z" fill="{HAIR}"/>'
        )
    if p.crest:
        e.append(
            f'<path d="M{cx-9},92 C{cx-7},{top-14} {cx+7},{top-14} {cx+9},92 Z" fill="{HAIR}"/>'
        )
    if p.bun:
        e.append(f'<circle cx="{cx}" cy="{top-2}" r="13" fill="{HAIR}"/>')
    if p.braids:
        for i in range(-3, 4):
            e.append(
                f'<rect x="{cx+i*11-2:.1f}" y="56" width="4" height="36" rx="2" fill="{HAIR}"/>'
            )
    return _svg("\n".join(e))


def profile(p: Hair) -> str:
    """Right-facing profile (nose toward +x)."""
    cx = 96.0
    top = 50 - p.top
    e: list[str] = []

    e.append(_shoulders())
    # neck
    e.append(f'<rect x="84" y="146" width="26" height="42" rx="11" fill="{SKIN}"/>')

    # back hair mass (falls behind, on the -x side)
    if p.afro:
        e.append(_curly_edge(cx - 4, 96, 48, 50, 22))
    elif not p.buzz:
        e.append(
            f'<path d="M{cx},{top} C{cx-46},{top} {cx-52},96 {cx-50},120 '
            f"L{cx-50},{p.back} C{cx-50},{p.back+16} {cx-18},{p.back+16} {cx-18},{p.back} "
            f'L{cx-18},120 C{cx-18},96 {cx-6},{top+6} {cx},{top} Z" fill="{HAIR}"/>'
        )

    # head/face profile (skin)
    e.append(
        f'<path d="M{cx-44},100 '
        f"C{cx-44},58 {cx-6},48 {cx+10},52 "
        f"C{cx+34},58 {cx+42},86 {cx+40},100 "
        f"C{cx+39},112 {cx+46},116 {cx+44},124 "  # nose/brow bump
        f"C{cx+42},132 {cx+34},132 {cx+30},134 "
        f"C{cx+30},150 {cx+12},158 {cx-6},156 "
        f'C{cx-30},154 {cx-44},134 {cx-44},100 Z" fill="{SKIN}"/>'
    )
    # ear
    e.append(f'<ellipse cx="{cx-12}" cy="112" rx="8" ry="12" fill="{SKIN_SHADE}"/>')

    # hair cap over the top of the head
    if p.buzz:
        e.append(f'<path d="M{cx-44},96 C{cx-44},54 {cx+22},50 {cx+34},84 '
                 f'L{cx-44},96 Z" fill="{HAIR}"/>')
    elif not p.afro:
        brow = 70 + p.fringe * 18
        e.append(
            f'<path d="M{cx-46},96 C{cx-46},{top+4} {cx+22},{top} {cx+34},{brow} '
            f'C{cx+18},{brow-8} {cx-24},{top+10} {cx-46},96 Z" fill="{HAIR}"/>'
        )
    # fringe down the forehead (front = +x side)
    if p.fringe >= 0.4 and not p.buzz and not p.afro:
        fy = 96 + p.fringe * 22
        e.append(
            f'<path d="M{cx+34},78 C{cx+40},{fy} {cx+30},{fy+4} {cx+24},{fy} '
            f'C{cx+22},96 {cx+24},84 {cx+34},78 Z" fill="{HAIR}"/>'
        )

    # specials
    if p.pomp:
        e.append(f'<path d="M{cx-30},86 C{cx-10},{top-12} {cx+34},{top+6} {cx+36},80 '
                 f'C{cx+16},74 {cx-16},74 {cx-30},86 Z" fill="{HAIR}"/>')
    if p.crest:
        e.append(f'<path d="M{cx-16},88 C{cx-10},{top-12} {cx+6},{top-12} {cx+8},88 Z" fill="{HAIR}"/>')
    if p.bun:
        e.append(f'<circle cx="{cx-18}" cy="{top+4}" r="13" fill="{HAIR}"/>')
    if p.ponytail:
        e.append(
            f'<path d="M{cx-44},86 C{cx-70},120 {cx-66},{p.back} {cx-50},{p.back} '
            f'C{cx-40},{p.back} {cx-36},120 {cx-30},96 Z" fill="{HAIR}"/>'
        )
    if p.braids:
        for i in range(5):
            yy = 60 + i * 6
            e.append(f'<path d="M{cx-44},{yy} C{cx-10},{yy-4} {cx+24},{yy} {cx+30},{yy+2}" '
                     f'stroke="{HAIR}" stroke-width="3" fill="none"/>')
    return _svg("\n".join(e))


def mirror(svg: str) -> str:
    """Mirror a profile to face the other way."""
    inner = svg.split(">", 1)[1].rsplit("</svg>", 1)[0]
    return _svg(f'<g transform="translate(200,0) scale(-1,1)">{inner}</g>')


def back(p: Hair) -> str:
    cx = 100.0
    top = 52 - p.top
    half = 40 + p.full
    e: list[str] = []

    e.append(_shoulders())
    e.append(f'<rect x="86" y="150" width="28" height="40" rx="11" fill="{SKIN}"/>')

    # full hair mass (no face on the back of the head)
    if p.afro:
        e.append(_curly_edge(cx, 96, half, half, 22))
    elif p.buzz:
        e.append(f'<ellipse cx="{cx}" cy="98" rx="42" ry="50" fill="{HAIR}"/>')
    else:
        e.append(
            f'<path d="M{cx-half},96 C{cx-half},{top} {cx+half},{top} {cx+half},96 '
            f"L{cx+half},{p.back} C{cx+half},{p.back+18} {cx-half},{p.back+18} "
            f'{cx-half},{p.back} Z" fill="{HAIR}"/>'
        )

    # centre part line
    if p.part == "center" and not p.buzz and not p.afro:
        e.append(
            f'<line x1="{cx}" y1="{top+6}" x2="{cx}" y2="{min(p.back, 150)}" '
            f'stroke="{SKIN_SHADE}" stroke-width="2" opacity="0.5"/>'
        )

    # specials
    if p.bun:
        e.append(f'<circle cx="{cx}" cy="{top+6}" r="15" fill="{HAIR}"/>')
    if p.ponytail:
        e.append(
            f'<path d="M{cx-16},90 C{cx-22},140 {cx-20},{p.back} {cx},{p.back} '
            f'C{cx+20},{p.back} {cx+22},140 {cx+16},90 Z" fill="{HAIR}"/>'
        )
    if p.braids:
        for i in range(-3, 4):
            e.append(
                f'<rect x="{cx+i*11-2:.1f}" y="{top+6}" width="4" height="{p.back-top-2:.0f}" '
                f'rx="2" fill="{HAIR}"/>'
            )
    return _svg("\n".join(e))


def generate() -> None:
    raw = yaml.safe_load(KB_PATH.read_text(encoding="utf-8"))
    kb_ids = [s["id"] for s in raw["styles"]]

    missing = [sid for sid in kb_ids if sid not in STYLE_FAMILY]
    if missing:
        raise SystemExit(f"No silhouette family mapped for: {missing}")

    count = 0
    for sid in kb_ids:
        fam = FAMILIES[STYLE_FAMILY[sid]]
        out = OUT_DIR / sid
        out.mkdir(parents=True, exist_ok=True)
        (out / "front.svg").write_text(front(fam), encoding="utf-8")
        right = profile(fam)
        (out / "right.svg").write_text(right, encoding="utf-8")
        (out / "left.svg").write_text(mirror(right), encoding="utf-8")
        (out / "back.svg").write_text(back(fam), encoding="utf-8")
        count += 4
    print(f"Generated {count} SVGs for {len(kb_ids)} styles into {OUT_DIR}")


if __name__ == "__main__":
    generate()
