"""Generate original, license-clean hairstyle illustrations (v2).

A polished, editorial flat-illustration look — refined head proportions,
gradient skin & hair with a sheen highlight, faded/tapered sides, texture
strokes, sideburns/stubble and subtle facial features — a big step up from the
earlier flat silhouettes. Barbershop-led, on-trend cuts.

Four views per style (front / left / right / back) plus a transparent
front-hair `overlay.svg` for the 2D try-on. Output:
    frontend/public/assets/hair/<style-id>/<name>.svg

Original artwork generated by this script (no third-party images).
Run from the repo root:  python tools/generate_hair_assets.py
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from pathlib import Path

import yaml

VIEWBOX = "0 0 240 300"

# palette
SKIN_TOP, SKIN_BOT = "#f2d3ba", "#e0b393"
SKIN_SHADE = "#d3a482"
HAIR_TOP, HAIR_MID, HAIR_BOT = "#413a48", "#2c2731", "#1e1b23"
SHEEN = "#6d6675"
GARMENT = "#3f4b5b"
BG_TOP, BG_BOT = "#f7f8fa", "#eaedf1"
STUBBLE = "#c9a98f"

REPO_ROOT = Path(__file__).resolve().parents[1]
KB_PATH = REPO_ROOT / "backend" / "app" / "knowledge" / "hairstyles.yaml"
OUT_DIR = REPO_ROOT / "frontend" / "public" / "assets" / "hair"

# Head reference (front). Face is centred at x=120; cheekbones (the try-on
# anchor points) sit near y=150 at x≈84 and x≈156.
CX = 120.0
CHEEK_Y = 150.0
CHEEK_HALF = 36.0  # -> cheek anchors at 84 / 156


@dataclass(frozen=True)
class Hair:
    """Parametric description of a cut."""

    top: float = 20.0  # hair height above the crown
    side: float = 168.0  # y the side hair reaches (168 ears .. 270 long)
    back: float = 168.0  # y the back hair reaches (back view)
    full: float = 8.0  # width beyond the head
    fringe: str = "none"  # none | fwd | curtain | edgar | brow
    part: str = "none"  # none | center | side
    fade: bool = False  # tapered/faded sides
    fade_y: float = 150.0  # where the fade fades out to skin
    curl: bool = False
    bun: bool = False
    ponytail: bool = False
    mullet: bool = False  # short sides, long tail at the back
    stubble: bool = True  # light beard shading (barbershop vibe)
    volume_front: bool = False  # pompadour/quiff lift


def _defs() -> str:
    return f"""<defs>
  <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="{BG_TOP}"/><stop offset="1" stop-color="{BG_BOT}"/>
  </linearGradient>
  <linearGradient id="skin" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="{SKIN_TOP}"/><stop offset="1" stop-color="{SKIN_BOT}"/>
  </linearGradient>
  <linearGradient id="hair" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="{HAIR_TOP}"/><stop offset="0.55" stop-color="{HAIR_MID}"/>
    <stop offset="1" stop-color="{HAIR_BOT}"/>
  </linearGradient>
  <linearGradient id="fade" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="{HAIR_MID}"/>
    <stop offset="1" stop-color="{HAIR_MID}" stop-opacity="0"/>
  </linearGradient>
  <linearGradient id="garment" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="{GARMENT}"/><stop offset="1" stop-color="#333d4a"/>
  </linearGradient>
</defs>"""


def _svg(inner: str, *, bg: bool = True) -> str:
    background = '<rect width="240" height="300" rx="18" fill="url(#bg)"/>' if bg else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VIEWBOX}" '
        f'width="240" height="300" role="img">\n{_defs()}\n{background}\n{inner}\n</svg>\n'
    )


# --- shared base (front) -------------------------------------------------


def _torso_neck() -> str:
    return (
        # shoulders
        '<path d="M44,300 C52,236 84,214 120,214 C156,214 188,236 196,300 Z" '
        'fill="url(#garment)"/>'
        # neck
        '<path d="M104,196 L136,196 L134,214 C128,222 112,222 106,214 Z" fill="url(#skin)"/>'
        f'<path d="M104,196 L136,196 L135,205 C128,210 112,210 105,205 Z" fill="{SKIN_SHADE}" '
        'opacity="0.5"/>'
    )


def _head() -> str:
    # A natural head: forehead, temples, cheekbones, tapering jaw, soft chin.
    return (
        '<path d="M120,58 '
        "C92,58 78,78 76,104 "  # left forehead/temple
        "C74,124 76,140 82,158 "  # left cheek
        "C88,178 100,196 120,198 "  # left jaw -> chin
        "C140,196 152,178 158,158 "  # right jaw
        "C164,140 166,124 164,104 "  # right cheek
        'C162,78 148,58 120,58 Z" fill="url(#skin)"/>'
        # che/temple soft shading
        f'<path d="M80,150 C86,172 100,190 120,192 C112,190 96,176 88,152 Z" '
        f'fill="{SKIN_SHADE}" opacity="0.35"/>'
        f'<path d="M160,150 C154,172 140,190 120,192 C128,190 144,176 152,152 Z" '
        f'fill="{SKIN_SHADE}" opacity="0.35"/>'
        # ears
        '<ellipse cx="76" cy="150" rx="8" ry="13" fill="url(#skin)"/>'
        '<ellipse cx="164" cy="150" rx="8" ry="13" fill="url(#skin)"/>'
    )


def _features() -> str:
    # Subtle, tasteful features so the face reads as a portrait, not a mannequin.
    return (
        # brows
        f'<path d="M96,132 q10,-5 20,-1" stroke="{HAIR_BOT}" stroke-width="3" '
        'fill="none" stroke-linecap="round" opacity="0.8"/>'
        f'<path d="M124,131 q10,-4 20,1" stroke="{HAIR_BOT}" stroke-width="3" '
        'fill="none" stroke-linecap="round" opacity="0.8"/>'
        # eyes
        f'<circle cx="104" cy="142" r="3.2" fill="{HAIR_BOT}"/>'
        f'<circle cx="136" cy="142" r="3.2" fill="{HAIR_BOT}"/>'
        # nose
        f'<path d="M120,146 L116,166 q4,4 8,0" stroke="{SKIN_SHADE}" stroke-width="2.5" '
        'fill="none" stroke-linecap="round" opacity="0.7"/>'
        # mouth
        f'<path d="M110,180 q10,6 20,0" stroke="{SKIN_SHADE}" stroke-width="2.5" '
        'fill="none" stroke-linecap="round" opacity="0.8"/>'
    )


def _stubble() -> str:
    # Faint jaw shading for the barbershop vibe.
    return (
        f'<path d="M86,166 C96,190 108,196 120,197 C132,196 144,190 154,166 '
        f'C150,182 138,193 120,194 C102,193 90,182 86,166 Z" fill="{STUBBLE}" '
        'opacity="0.45"/>'
    )


# --- hair (front) --------------------------------------------------------


def _fade_sides(p: Hair) -> str:
    """Tapered/faded temporal sides: hair up top fading to skin lower down."""
    if not p.fade:
        return ""
    top = 96
    return (
        f'<path d="M74,{top} C70,120 70,140 74,{p.fade_y} L88,{p.fade_y} '
        f'C86,130 86,112 90,{top} Z" fill="url(#fade)"/>'
        f'<path d="M166,{top} C170,120 170,140 166,{p.fade_y} L152,{p.fade_y} '
        f'C154,130 154,112 150,{top} Z" fill="url(#fade)"/>'
    )


def _back_mass(p: Hair) -> str:
    """Hair volume behind the head (length + fullness), drawn before the face."""
    half = CHEEK_HALF + 8 + p.full
    top = 58 - p.top
    if p.curl:
        return _curly_blob(CX, 108, half + 4, half + 2)
    return (
        f'<path d="M{CX-half},120 C{CX-half},{top} {CX+half},{top} {CX+half},120 '
        f"L{CX+half},{p.side} C{CX+half},{p.side+18} {CX-half},{p.side+18} "
        f'{CX-half},{p.side} Z" fill="url(#hair)"/>'
    )


def _curly_blob(cx: float, cy: float, rx: float, ry: float, n: int = 26) -> str:
    pts = []
    for i in range(n):
        a = 2 * math.pi * i / n
        bump = 1.0 + (0.12 if i % 2 == 0 else -0.03)
        pts.append((cx + rx * bump * math.cos(a), cy + ry * bump * math.sin(a)))
    d = "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + " Z"
    return f'<path d="{d}" fill="url(#hair)"/>'


def _top(p: Hair) -> str:
    """Hair on the crown, shaped by volume + fringe, with a sheen highlight."""
    if p.curl and not p.mullet:
        # curly/textured top
        base = _curly_blob(CX, 92, 48, 40, 24)
        return base + _sheen(CX - 14, 78, 22, 12)

    top = 58 - p.top
    # main cap from temple to temple, down to the hairline/brow
    if p.volume_front:
        cap = (
            f'<path d="M74,110 C70,{top-16} {CX},{top-26} {CX},{top-24} '
            f'C{CX},{top-26} 170,{top-16} 166,110 '
            f"C150,96 90,96 74,110 Z\" fill=\"url(#hair)\"/>"
        )
    else:
        brow = 104 + (14 if p.fringe in ("fwd", "edgar", "brow") else 0)
        cap = (
            f'<path d="M72,112 C70,{top} 170,{top} 168,112 '
            f'C150,{brow} 90,{brow} 72,112 Z" fill="url(#hair)"/>'
        )
    return cap + _fringe(p) + _sheen(CX - 30, top + 12, 26, 10)


def _fringe(p: Hair) -> str:
    if p.fringe == "none":
        return ""
    if p.fringe == "curtain":
        return (
            f'<path d="M{CX},108 C{CX-18},120 {CX-30},128 {CX-40},120 '
            f'C{CX-34},104 {CX-14},100 {CX},108 Z" fill="url(#hair)"/>'
            f'<path d="M{CX},108 C{CX+18},120 {CX+30},128 {CX+40},120 '
            f'C{CX+34},104 {CX+14},100 {CX},108 Z" fill="url(#hair)"/>'
        )
    if p.fringe == "edgar":
        # straight, blunt forward fringe (edgar / caesar)
        return f'<path d="M74,120 L166,120 L164,110 L76,110 Z" fill="url(#hair)"/>'
    # forward / brow-skimming textured fringe
    return (
        f'<path d="M74,112 C96,132 144,132 166,112 '
        f'C150,124 90,124 74,112 Z" fill="url(#hair)"/>'
    )


def _sheen(x: float, y: float, w: float, h: float) -> str:
    return f'<ellipse cx="{x}" cy="{y}" rx="{w}" ry="{h}" fill="{SHEEN}" opacity="0.22"/>'


def _specials(p: Hair) -> str:
    out = ""
    if p.bun:
        out += f'<circle cx="{CX}" cy="{58-p.top-4}" r="15" fill="url(#hair)"/>'
        out += _sheen(CX - 5, 58 - p.top - 8, 7, 4)
    if p.mullet:
        # long tail at the nape
        out += (
            f'<path d="M92,150 C86,180 90,{p.back} {CX},{p.back} '
            f'C{CX+42},{p.back-2} {CX+30},172 148,150 '
            f'C140,168 100,168 92,150 Z" fill="url(#hair)"/>'
        )
    return out


def front(p: Hair) -> str:
    e = [_back_mass(p) if p.side > 168 or p.curl else ""]
    e.append(_specials(p))
    e.append(_torso_neck())
    e.append(_head())
    if p.stubble:
        e.append(_stubble())
    e.append(_features())
    e.append(_fade_sides(p))
    e.append(_top(p))
    # sideburns
    e.append(
        f'<path d="M78,120 L84,120 L84,{min(p.fade_y, 150)} L78,{min(p.fade_y, 150)} Z" '
        'fill="url(#hair)" opacity="0.9"/>'
    )
    e.append(
        f'<path d="M156,120 L162,120 L162,{min(p.fade_y, 150)} L156,{min(p.fade_y, 150)} Z" '
        'fill="url(#hair)" opacity="0.9"/>'
    )
    return _svg("\n".join(x for x in e if x))


def overlay(p: Hair) -> str:
    """Front hair only, transparent — for the 2D try-on overlay."""
    e = [
        _back_mass(p) if p.side > 168 or p.curl else "",
        _specials(p),
        _fade_sides(p),
        _top(p),
    ]
    return _svg("\n".join(x for x in e if x), bg=False)


# --- profile + back (simpler, gradient-matched) --------------------------


def profile(p: Hair) -> str:
    top = 58 - p.top
    e = [_torso_neck()]
    # back hair mass on the -x side
    if p.curl:
        e.append(_curly_blob(104, 108, 46, 48, 24))
    else:
        e.append(
            f'<path d="M120,{top} C86,{top} 74,110 76,132 L76,{p.back} '
            f"C76,{p.back+16} 104,{p.back+16} 104,{p.back} L104,132 "
            f'C104,110 112,{top+6} 120,{top} Z" fill="url(#hair)"/>'
        )
    # face profile (skin)
    e.append(
        f'<path d="M92,196 C74,192 66,168 66,132 '
        "C66,92 92,64 120,66 "
        "C150,68 168,96 166,128 "
        "C165,142 174,146 172,156 "  # nose
        "C170,166 160,166 156,168 "
        'C156,188 128,200 92,196 Z" fill="url(#skin)"/>'
    )
    e.append('<ellipse cx="104" cy="150" rx="8" ry="12" fill="url(#skin)"/>')
    if p.stubble:
        e.append(
            f'<path d="M96,176 C110,192 140,190 154,170 C146,186 120,196 96,190 Z" '
            f'fill="{STUBBLE}" opacity="0.4"/>'
        )
    # brow + eye
    e.append(f'<circle cx="128" cy="132" r="3" fill="{HAIR_BOT}"/>')
    # hair cap over the head
    if p.volume_front:
        e.append(
            f'<path d="M66,120 C64,{top-14} 150,{top-6} 158,104 '
            f'C140,96 84,100 66,120 Z" fill="url(#hair)"/>'
        )
    elif p.curl:
        pass
    else:
        e.append(
            f'<path d="M66,124 C64,{top} 150,{top-4} 158,112 '
            f'C138,102 86,104 66,124 Z" fill="url(#hair)"/>'
        )
    e.append(_fade_prof(p))
    if p.bun:
        e.append(f'<circle cx="86" cy="{top+6}" r="15" fill="url(#hair)"/>')
    if p.ponytail or p.mullet:
        e.append(
            f'<path d="M72,120 C46,150 52,{p.back} 72,{p.back} '
            f'C82,{p.back} 86,150 92,124 Z" fill="url(#hair)"/>'
        )
    e.append(_sheen(96, top + 16, 22, 9))
    return _svg("\n".join(x for x in e if x))


def _fade_prof(p: Hair) -> str:
    if not p.fade:
        return ""
    return f'<path d="M108,110 C104,128 104,142 108,{p.fade_y} L128,{p.fade_y} C124,132 124,116 128,110 Z" fill="url(#fade)"/>'


def mirror(svg: str) -> str:
    inner = svg.split(">", 1)[1].rsplit("</svg>", 1)[0]
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VIEWBOX}" '
        f'width="240" height="300" role="img"><g transform="translate(240,0) scale(-1,1)">'
        f"{inner}</g></svg>\n"
    )


def back(p: Hair) -> str:
    top = 58 - p.top
    half = CHEEK_HALF + 8 + p.full
    e = [_torso_neck()]
    if p.curl:
        e.append(_curly_blob(CX, 116, half + 4, half + 4, 26))
    else:
        e.append(
            f'<path d="M{CX-half},120 C{CX-half},{top} {CX+half},{top} {CX+half},120 '
            f"L{CX+half},{p.back} C{CX+half},{p.back+18} {CX-half},{p.back+18} "
            f'{CX-half},{p.back} Z" fill="url(#hair)"/>'
        )
    if p.fade:
        e.append(
            f'<path d="M{CX-half},{p.fade_y} C{CX-half+2},{p.fade_y+18} '
            f'{CX+half-2},{p.fade_y+18} {CX+half},{p.fade_y} '
            f'L{CX+half},{p.back} L{CX-half},{p.back} Z" fill="url(#bg)" opacity="0"/>'
        )
    if p.part == "center":
        e.append(
            f'<line x1="{CX}" y1="{top+8}" x2="{CX}" y2="{min(p.back,180)}" '
            f'stroke="{HAIR_BOT}" stroke-width="2" opacity="0.4"/>'
        )
    if p.bun:
        e.append(f'<circle cx="{CX}" cy="{top+8}" r="17" fill="url(#hair)"/>')
    if p.ponytail or p.mullet:
        e.append(
            f'<path d="M104,110 C98,150 100,{p.back} {CX},{p.back} '
            f'C{CX+20},{p.back} {CX+22},150 136,110 Z" fill="url(#hair)"/>'
        )
    e.append(_sheen(CX - 10, top + 20, 26, 10))
    return _svg("\n".join(x for x in e if x))


