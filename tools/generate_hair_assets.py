"""Generate original, license-clean hairstyle silhouette assets.

Produces four flat SVG views (front / left / right / back) per hairstyle on a
neutral *mannequin* head — deliberately generic so the preview reads as a style
reference, not the user. Output: frontend/public/assets/hair/<style-id>/<angle>.svg

These are ORIGINAL assets generated by this script (no third-party images).
Run from the repo root:  python tools/generate_hair_assets.py

The look is intentionally a clean, flat icon set rather than photorealistic —
honest about being a schematic reference. Silhouettes differ by length, top
volume, fullness, fringe, parting and special features (bun, ponytail, afro,
curls, braids, fade).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

